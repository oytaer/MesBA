// ============================================================================
// 浮点到 uint8 量化辅助函数（仅在初始化和训练阶段使用）
// ============================================================================
// 注意：MesBA 运行时全程零浮点，这些函数仅在：
//   1. 从外部数据源导入权重
//   2. 训练后写入新权重
//   3. 加载模型快照
// 时使用，不进入推理热路径。

/// 将 [0.0, 1.0] 范围的 float 量化为 uint8
/// 超过范围的值会被钳位到 [0, 255]
pub fn quantize_f32_to_u8(value: f32) -> u8 {
    let clamped = value.clamp(0.0, 1.0);
    (clamped * 255.0).round() as u8
}

/// 将 uint8 反量化为 [0.0, 1.0] 范围的 float（仅用于日志/可视化）
pub fn dequantize_u8_to_f32(value: u8) -> f32 {
    value as f32 / 255.0
}

// ============================================================================
// 单元测试
// ============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_q8_constants() {
        // 验证常量值在合理范围
        const {
            assert!(Q8_8_0_90 > Q8_8_0_80);
            assert!(Q8_8_0_80 > Q8_8_0_70);
            assert!(Q8_8_0_50 == 128);
            assert!(Q8_8_0_10 > Q8_8_0_05);
        }
    }

    #[test]
    fn test_quantize() {
        assert_eq!(quantize_f32_to_u8(0.0), 0);
        assert_eq!(quantize_f32_to_u8(1.0), 255);
        assert_eq!(quantize_f32_to_u8(0.5), 128);
        assert_eq!(quantize_f32_to_u8(-0.5), 0);   // 钳位到0
        assert_eq!(quantize_f32_to_u8(1.5), 255);   // 钳位到255
    }

    #[test]
    fn test_dequantize() {
        assert!(dequantize_u8_to_f32(0) < 0.001);
        assert!((dequantize_u8_to_f32(255) - 1.0).abs() < 0.001);
        assert!((dequantize_u8_to_f32(128) - 0.5).abs() < 0.01);
    }
}

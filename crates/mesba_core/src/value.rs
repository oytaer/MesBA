// ============================================================================
// Q8.8 定点小数常量定义
// ============================================================================
// Q8.8 格式：高8位整数部分，低8位小数部分
// uint8 值 v 对应的 Q8.8 小数 = v / 255.0（近似）
// 下面是设计文档中列出的关键初始权重值对应的 uint8 常量


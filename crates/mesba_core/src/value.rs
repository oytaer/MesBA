pub const Q8_8_ONE: u8 = 255;

/// Q8.8: 0.85 的 uint8 表示 ≈ 218（218/255 ≈ 0.85）
pub const Q8_8_0_85: u8 = 218;

/// Q8.8: 0.90 的 uint8 表示 ≈ 230（230/255 ≈ 0.90）
pub const Q8_8_0_90: u8 = 230;

/// Q8.8: 0.80 的 uint8 表示 ≈ 204（204/255 ≈ 0.80）
pub const Q8_8_0_80: u8 = 204;

/// Q8.8: 0.70 的 uint8 表示 ≈ 179（179/255 ≈ 0.70）
pub const Q8_8_0_70: u8 = 179;

/// Q8.8: 0.60 的 uint8 表示 ≈ 153（153/255 ≈ 0.60）
pub const Q8_8_0_60: u8 = 153;

/// Q8.8: 0.50 的 uint8 表示 = 128
pub const Q8_8_0_50: u8 = 128;

/// Q8.8: 0.30 的 uint8 表示 ≈ 77
pub const Q8_8_0_30: u8 = 77;

/// Q8.8: 0.20 的 uint8 表示 ≈ 51
pub const Q8_8_0_20: u8 = 51;

/// Q8.8: 0.10 的 uint8 表示 ≈ 26
pub const Q8_8_0_10: u8 = 26;

/// Q8.8: 0.05 的 uint8 表示 ≈ 13
pub const Q8_8_0_05: u8 = 13;

